def main() -> None:
    entries = []
    for row in ROWS:
        (typ, minp, profiles, cap, direction, senders, dests, qos, qos_ok,
         ack, idem, resp, before, security, schema) = row
        entries.append({
            "type": typ,
            "min_protocol": minp,
            "max_protocol": None,
            "profiles": profiles,
            "required_capability": cap,
            "direction": direction,
            "valid_senders": senders,
            "valid_destinations": dests,
            "qos_default": qos,
            "qos_allowed": qos_ok,
            "ack": ack,
            "idempotent": idem,
            "idempotency_key": "payload.idempotency_key" if idem else None,
            "response_type": resp,
            "correlation": "copy_or_message_id",
            "causation": "set_on_derived_state",
            "legal_before_handshake": before,
            "security_class": security,
            "schema": schema,
        })
    out = ROOT / "schema" / "registry.json"
    payload = json.dumps({"version": "1.2", "messages": entries}, indent=2) + "\n"
    out.write_text(payload)
    packaged = ROOT / "python" / "src" / "acp" / "data" / "registry.json"
    packaged.parent.mkdir(parents=True, exist_ok=True)
    packaged.write_text(payload)
    print(f"wrote {out} ({len(entries)} messages)")


if __name__ == "__main__":
    main()
